export const catalogWorks: CatalogWork[] = Object.entries(categoriesByNumber)
  .sort(([numberA], [numberB]) => Number(numberA) - Number(numberB))
  .map(([number, categories], index) => {
    const primary = categories[0];
    const detail = catalogCategoryDetails[primary];
    const catalogPage = catalogPageByNumber[number];

    return {
      id: `catalog-${number}`,
      number,
      title: `Project No. ${number}`,
      titleTh: `ผลงานหมายเลข ${number}`,
      category: detail.eyebrow,
      categories,
      materials: detail.materials,
      description: detail.description,
      imageUrl: sitePath(
        `/catalog-2026/${number === '35' ? '35-hq' : number}.${number === '03' ? 'png' : 'jpg'}`,
      ),
      fullImageUrl: sitePath(`/catalog-full/${number}.${catalogPage === 120 ? 'png' : 'jpg'}`),
      catalogPage,
      objectKey: null,
      year: '2026',
      sortOrder: index,
      createdAt: '',
    };
  });

